
N = int(input())

# 1. 메모장(dp 테이블) 만들기
# dp[i]는 숫자 i를 1로 만드는 최소 연산 횟수 저장
dp = [0] * (N + 1)

# 2. 2부터 N까지 차례대로 최솟값을 계산 (Bottom-Up 방식)
for i in range(2, N + 1):
    # 기본 전략: 1을 빼는 경우 (i-1의 결과에서 연산 1회 추가)
    dp[i] = dp[i - 1] + 1
    
    # 만약 2로 나누어 떨어진다면?
    if i % 2 == 0:
        # '1을 뺀 경우'와 '2로 나눈 경우' 중 더 작은 횟수를 선택
        dp[i] = min(dp[i], dp[i // 2] + 1)
        
    # 만약 3으로 나누어 떨어진다면?
    if i % 3 == 0:
        # 현재 저장된 값과 '3으로 나눈 경우' 중 더 작은 횟수를 선택
        dp[i] = min(dp[i], dp[i // 3] + 1)

print(dp[N])